function inRing(ring: Ring, lon: number, lat: number): boolean {
  let inside = false;
  const n = ring.length / 2;
  let j = n - 1;
  for (let i = 0; i < n; i++) {
    const xi = ring[i * 2] ?? 0;
    const yi = ring[i * 2 + 1] ?? 0;
    const xj = ring[j * 2] ?? 0;
    const yj = ring[j * 2 + 1] ?? 0;
    if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
    j = i;
  }
  return inside;
}

export function isLand(lon: number, lat: number): boolean {
  for (const w of WATER) if (inRing(w, lon, lat)) return false;
  for (const r of LAND) if (inRing(r, lon, lat)) return true;
  return false;
}

export type LandDot = { lat: number; lon: number };

let cache: LandDot[] | null = null;

/** Evenly spaced land samples (spacing in degrees of latitude; longitude step widens toward the poles). */
export function landDots(step = 2.6): LandDot[] {
  if (cache) return cache;
  const out: LandDot[] = [];
  for (let lat = -84; lat <= 84; lat += step) {
    const lonStep = step / Math.max(0.2, Math.cos((lat * Math.PI) / 180));
    for (let lon = -180; lon < 180; lon += lonStep) {
      if (isLand(lon, lat)) out.push({ lat, lon });
    }
  }
  cache = out;
  return out;
}
