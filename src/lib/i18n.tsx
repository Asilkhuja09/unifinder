type I18nValue = {
  lang: LangCode;
  setLang: (l: LangCode) => void;
  t: (key: keyof Dict) => string;
  tt: (text: string) => string;
  dir: "ltr" | "rtl";
};

const I18nContext = createContext<I18nValue | null>(null);

const CACHE_PREFIX = "uf_i18n_";
const LANG_KEY = "uf_lang";

function loadCache(lang: LangCode): Record<string, string> {
  try {
    const raw = localStorage.getItem(CACHE_PREFIX + lang);
    return raw ? (JSON.parse(raw) as Record<string, string>) : {};
  } catch {
    return {};
  }
}

function saveCache(lang: LangCode, cache: Record<string, string>) {
  try {
    localStorage.setItem(CACHE_PREFIX + lang, JSON.stringify(cache));
  } catch {
    /* storage full — keep in-memory only */
  }
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<LangCode>("en");
  const setLang = useCallback((l: LangCode) => {
    setLangState(l);
    try {
      localStorage.setItem(LANG_KEY, l);
    } catch {
      /* private mode — language still changes for this page */
    }
  }, []);

  // Restore the saved language after hydration (each route has its own provider).
  useEffect(() => {
    try {
      const saved = localStorage.getItem(LANG_KEY);
      if (saved && LANGUAGES.some((l) => l.code === saved)) setLangState(saved as LangCode);
    } catch {
      /* ignore */
    }
  }, []);
  const [cache, setCache] = useState<Record<string, string>>({});
  const pendingRef = useRef<Set<string>>(new Set());
  const flushingRef = useRef(false);
  const cacheRef = useRef<Record<string, string>>({});
  /** Strings that could not be translated, with the time of failure – retried later, never in a loop. */
  const failedRef = useRef<Map<string, number>>(new Map());
  const langRef = useRef<LangCode>("en");
  const dir: "ltr" | "rtl" = lang === "ar" ? "rtl" : "ltr";

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = dir;
  }, [lang, dir]);

  useEffect(() => {
    langRef.current = lang;
    cacheRef.current = loadCache(lang);
    pendingRef.current = new Set();
    failedRef.current = new Map();
    setCache({ ...cacheRef.current });
  }, [lang]);

  const flush = useCallback(async () => {
    if (flushingRef.current) return;
    flushingRef.current = true;
    try {
      while (pendingRef.current.size > 0) {
        // Always serve whichever language is current: `pendingRef` is reset on every switch.
        const batchLang = langRef.current;
        if (batchLang === "en") break;
        const batch = takeBatch(pendingRef.current);
        const langName = LANGUAGES.find((l) => l.code === batchLang)?.label ?? batchLang;
        const { done, failed } = await translateWithFallback(batch, async (texts) => {
          const { translations } = await translateBatch({
            data: { lang: batchLang, langName, texts },
          });
          return translations;
        });
        // The visitor switched language while this request was in flight – drop the answer.
        if (langRef.current !== batchLang) continue;
        failed.forEach((source) => failedRef.current.set(source, Date.now()));
        if (failed.length > 0) console.error("Could not translate", failed.length, "string(s)");
        Object.assign(cacheRef.current, done);
        saveCache(batchLang, cacheRef.current);
        setCache({ ...cacheRef.current });
      }
    } finally {
      flushingRef.current = false;
    }
  }, []);

  const t = useCallback(
    (key: keyof Dict) => dict[lang]?.[key] ?? en[key],
    [lang],
  );

  const tt = useCallback(
    (text: string) => {
      if (lang === "en" || !text.trim()) return text;
      const hit = cache[text];
      if (hit) return hit;
      if (
        text.length <= MAX_TEXT_CHARS &&
        !pendingRef.current.has(text) &&
        Date.now() - (failedRef.current.get(text) ?? 0) > RETRY_AFTER_MS &&
        !(text in cacheRef.current)
      ) {
        pendingRef.current.add(text);
        queueMicrotask(() => void flush());
      }
      return text;
    },
    [lang, cache, flush],
  );

  const value = useMemo(
    () => ({ lang, setLang, t, tt, dir }),
    [lang, setLang, t, tt, dir],
  );
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used inside I18nProvider");
  return ctx;
}